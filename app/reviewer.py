from .config import settings
from .github_client import GitHubClient
from .analyzer import analyze
from .db import save_review

def build_diff(files):
    chunks = []
    for item in files[:settings.max_files]:
        patch = item.get("patch")
        if not patch:
            continue
        chunks.append(f"\n### FILE: {item.get('filename')}\nSTATUS: {item.get('status')}\n{patch}")
    diff = "\n".join(chunks)
    return diff[:settings.max_patch_chars]

def format_comment(title, findings, summary):
    lines = ["## 🛡️ PR Guardian review", "", summary or "Automated review completed.", ""]
    if not findings:
        lines += ["<sub>No actionable findings were returned. This is not a guarantee that the code is bug-free.</sub>"]
    else:
        lines += [f"**{len(findings)} finding(s)**", ""]
        for i, f in enumerate(findings, 1):
            location = f"`{f.file or 'file not specified'}`"
            if f.line:
                location += f", line {f.line}"
            lines += [
                f"### {i}. [{f.severity.upper()}] {f.title}",
                f"**Location:** {location}",
                f"**Why it matters:** {f.explanation}",
                f"**Suggested action:** {f.recommendation}",
                f"<sub>Reviewer: {f.source} · Confidence: {f.confidence:.0%}</sub>",
                ""
            ]
    lines += ["---", "<sub>Generated by PR Guardian using an open-weight model. AI findings can be incorrect; verify before changing code or merging.</sub>"]
    return "\n".join(lines)

async def review_pull_request(repo, number):
    gh = GitHubClient()
    pr = await gh.get_pull(repo, number)
    files = await gh.get_files(repo, number)
    diff = build_diff(files)
    if not diff:
        summary = "No textual diff patches were available to analyze (binary, generated, or unsupported files may be present)."
        findings = []
    else:
        findings, summary = await analyze(diff)
    body = format_comment(pr.get("title", ""), findings, summary)
    status = "dry_run" if settings.dry_run else "posted"
    if not settings.dry_run:
        await gh.post_comment(repo, number, body)
    save_review(repo, number, pr.get("title", ""), status,
                [f.model_dump() for f in findings], summary)
    return {"repo": repo, "number": number, "title": pr.get("title"),
            "status": status, "findings": [f.model_dump() for f in findings],
            "summary": summary, "comment_preview": body}
